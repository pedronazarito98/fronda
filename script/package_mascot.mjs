// Regenerate the offline motion engine from the approved preview, without dependencies.
import { readFile, writeFile, copyFile, mkdir } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
const root = new URL('../', import.meta.url);
const source = new URL('output/mascot-animation/fronda-v1/src/', root);
const destination = new URL('Resources/FrondaAnimation/', root);
await mkdir(destination, { recursive: true });
const modules = ['rig', 'states', 'motion-spring', 'organic-motion', 'motion'];
const parts = [];
for (const name of modules) {
  const typed = await readFile(new URL(`${name}.ts`, source), 'utf8');
  const code = stripTypeScriptTypes(typed, { mode: 'strip' })
    .replace(/^import .*;\s*$/gm, '').replace(/^export /gm, '');
  parts.push(code);
}
parts.push(`
const mascot = new MascotMotion();
function configureMascot(state, reduced, pointerX, pointerY, hover, velocityX, velocityY, dragging) {
  if (mascot.state !== state) mascot.select(state);
  mascot.reduced = reduced;
  mascot.interaction.gaze = { x: pointerX, y: pointerY };
  mascot.interaction.hover = hover;
  mascot.interaction.velocity = { x: velocityX, y: velocityY };
  mascot.interaction.dragging = Boolean(dragging);
}
function touchMascot(branch) { mascot.touch(branch); }
function mascotFrame(delta) {
  let f = mascot.step(delta);
  if (mascot.reduced) for (let i = 0; i < 60; i++) f = mascot.step(.016);
  return [...f.angles, ...f.caps, ...f.bends, ...f.growth, ...f.blooms,
    ...f.filaments, ...f.tips, ...f.color, ...f.gaze, ...f.body, ...f.position, f.blink, f.time, BASE_SCALE];
}
`);
await writeFile(new URL('motion.js', destination), `// Generated by script/package_mascot.mjs. Source: approved Fronda preview.\n${parts.join('\n')}\n`);
await copyFile(new URL('output/mascot-animation/fronda-v1/assets/fronda-neutral.png', root), new URL('mascot.png', destination));
console.log('Packaged approved mascot motion and texture.');
const shaderSource = stripTypeScriptTypes(await readFile(new URL('shaders.ts', source), 'utf8'), { mode: 'strip' }).replace(/^export /gm, '');
const shaders = new Function(`${shaderSource}; return { VERTEX_SHADER, FRAGMENT_SHADER };`)();
const rigSource = stripTypeScriptTypes(await readFile(new URL('rig.ts', source), 'utf8'), { mode: 'strip' }).replace(/^import .*;\s*$/gm, '').replace(/^export /gm, '');
const rig = new Function(`${rigSource}; return { PIVOTS, CROWNS, TIPS, EYES };`)();
let vertex = shaders.VERTEX_SHADER.slice(shaders.VERTEX_SHADER.indexOf('vec2 rotate'));
vertex = vertex.replace('void main() {', `vertex VertexOut mascotVertex(uint id [[vertex_id]], constant float *data [[buffer(0)]], constant float *u [[buffer(1)]]) {
  VertexOut out;
  float2 aUV(data[id*7],data[id*7+1]);
  float4 aFilament(data[id*7+2],data[id*7+3],data[id*7+4],data[id*7+5]);
  float aFilamentBranch=data[id*7+6];
  float4 uBody(u[55],u[56],u[57],u[58]);
  float2 uPosition(u[59],u[60]);
  float uTime=u[62], uScale=u[63];`)
  .replace('vUV = aUV;', 'out.uv = aUV;')
  .replace('gl_Position =', 'out.position =')
  .replace(/\}\s*$/, 'return out; }');
const offsets = { uAngle: 0, uCap: 5, uBend: 10, uGrowth: 15, uBloom: 20, uTipStrength: 45 };
let fragment = shaders.FRAGMENT_SHADER.slice(shaders.FRAGMENT_SHADER.indexOf('void main()'));
fragment = fragment.replace('void main() {', `fragment float4 mascotFragment(VertexOut in [[stage_in]], constant float *u [[buffer(1)]], texture2d<float> uTexture [[texture(0)]]) {
  constexpr sampler textureSampler(coord::normalized,address::clamp_to_edge,filter::linear);
  float2 vUV=in.uv, uGaze(u[53],u[54]);
  float3 uColor(u[50],u[51],u[52]);
  float uBlink=u[61];`)
  .replace('texture2D(uTexture,sampleUV)', 'uTexture.sample(textureSampler,sampleUV)')
  .replace('discard;', 'discard_fragment();').replace('gl_FragColor =', 'return');
function metal(code) {
  for (const [name, offset] of Object.entries(offsets)) code = code.replaceAll(`${name}[i]`, `u[${offset}+i]`);
  return code.replaceAll('uFilament[i]', 'float4(u[25+i*4],u[26+i*4],u[27+i*4],u[28+i*4])')
    .replaceAll('vec2', 'float2').replaceAll('vec3', 'float3').replaceAll('vec4', 'float4');
}
const constants = Object.entries({ uPivot: rig.PIVOTS, uCrown: rig.CROWNS, uTip: rig.TIPS, uEyes: rig.EYES })
  .map(([name, values]) => `constant float${values[0].length} ${name}[${values.length}] = {${values.map(v => `float${v.length}(${v.join(',')})`).join(',')}};`).join('\n');
await writeFile(new URL('mascot.metal.txt', destination), `// Generated from the approved WebGL deformation.\n#include <metal_stdlib>\nusing namespace metal;\nstruct VertexOut { float4 position [[position]]; float2 uv; };\n${constants}\n${metal(vertex)}\n${metal(fragment)}\n`);
const filamentSource = stripTypeScriptTypes(await readFile(new URL('filaments.ts', source), 'utf8'), {mode:'strip'}).replace(/^import .*;\s*$/gm, '').replace(/^export /gm, '');
const binding = new Function(`${rigSource}\n${filamentSource}\nreturn filamentBinding;`)();
const vertices = [], indices = [], divisions = 160;
for(let y=0;y<=divisions;y++) for(let x=0;x<=divisions;x++) vertices.push(x/divisions,y/divisions,...binding([x/divisions,y/divisions]));
for(let y=0;y<divisions;y++) for(let x=0;x<divisions;x++) { const a=y*(divisions+1)+x,b=a+divisions+1; indices.push(a,b,a+1,a+1,b,b+1); }
await writeFile(new URL('vertices.bin',destination), new Uint8Array(new Float32Array(vertices).buffer));
await writeFile(new URL('indices.bin',destination), new Uint8Array(new Uint16Array(indices).buffer));
console.log('Packaged native Metal shaders and mesh.');
